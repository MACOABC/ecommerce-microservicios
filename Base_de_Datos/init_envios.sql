BEGIN;
CREATE TABLE envios (
 id UUID PRIMARY KEY,
 orden_id UUID NOT NULL UNIQUE,
 guia VARCHAR(40) NOT NULL UNIQUE,
 destinatario VARCHAR(100) NOT NULL,
 direccion VARCHAR(240) NOT NULL,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PREPARANDO','DESPACHADO','EN_TRANSITO','ENTREGADO')),
 creado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE envio_eventos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 envio_id UUID NOT NULL REFERENCES envios(id),
 estado VARCHAR(20) NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
