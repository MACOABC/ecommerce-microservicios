BEGIN;
CREATE TABLE categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL UNIQUE CHECK (length(trim(nombre)) > 0)
);
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
 descripcion VARCHAR(1000) NOT NULL DEFAULT '',
 precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
 stock INTEGER NOT NULL CHECK (stock >= 0),
 categoria_id BIGINT NOT NULL REFERENCES categorias(id),
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
-- Una reserva idempotente por orden; guarda precios y nombres al comprar.
CREATE TABLE reservas (
 orden_id UUID PRIMARY KEY,
 estado VARCHAR(12) NOT NULL CHECK (estado IN ('RESERVADA','LIBERADA'))
);
CREATE TABLE reserva_items (
 orden_id UUID NOT NULL REFERENCES reservas(orden_id),
 producto_id BIGINT NOT NULL REFERENCES productos(id),
 nombre VARCHAR(120) NOT NULL,
 cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 999),
 precio NUMERIC(12,2) NOT NULL,
 PRIMARY KEY (orden_id, producto_id)
);
